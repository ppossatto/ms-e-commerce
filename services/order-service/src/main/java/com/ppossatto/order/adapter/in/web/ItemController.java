package com.ppossatto.order.adapter.in.web;

import com.ppossatto.order.domain.model.Item;
import com.ppossatto.order.domain.model.ItemNotInCatalogException;
import com.ppossatto.order.domain.port.in.CreateItemUseCase;
import com.ppossatto.order.domain.port.in.CreateItemUseCase.CreateItemCommand;
import com.ppossatto.order.domain.port.in.FindItemUseCase;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotBlank;
import java.net.URI;
import java.util.UUID;
import org.springframework.http.HttpStatusCode;
import org.springframework.http.ProblemDetail;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.ExceptionHandler;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

/**
 * Hand-written to keep the example self-contained.
 * With an OpenAPI contract, implement the interface generated by openapi-generator.
 */
@RestController
@RequestMapping("/items")
class ItemController {

    private final CreateItemUseCase createItem;
    private final FindItemUseCase findItem;

    ItemController(CreateItemUseCase createItem, FindItemUseCase findItem) {
        this.createItem = createItem;
        this.findItem = findItem;
    }

    @PostMapping
    ResponseEntity<ItemResponse> create(@Valid @RequestBody CreateItemRequest request) {
        Item item = createItem.create(new CreateItemCommand(request.sku(), request.name()));
        return ResponseEntity.created(URI.create("/items/" + item.id())).body(ItemResponse.from(item));
    }

    @GetMapping("/{id}")
    ResponseEntity<ItemResponse> findById(@PathVariable UUID id) {
        return ResponseEntity.of(findItem.findById(id).map(ItemResponse::from));
    }

    @ExceptionHandler(ItemNotInCatalogException.class)
    ProblemDetail handleNotInCatalog(ItemNotInCatalogException ex) {
        return ProblemDetail.forStatusAndDetail(HttpStatusCode.valueOf(422), ex.getMessage());
    }

    record CreateItemRequest(@NotBlank String sku, @NotBlank String name) {}

    record ItemResponse(UUID id, String sku, String name) {
        static ItemResponse from(Item item) {
            return new ItemResponse(item.id(), item.sku(), item.name());
        }
    }
}
